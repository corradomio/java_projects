"""Generate NamedColors and its reference fixture using matplotlib==3.11.2."""
from pathlib import Path
import json
import matplotlib
from matplotlib.colors import CSS4_COLORS, get_named_colors_mapping, to_hex

if matplotlib.__version__ != "3.11.2":
    raise RuntimeError("Install matplotlib==3.11.2 to reproduce this catalog")

root = Path(__file__).resolve().parents[1]
dest = root / "src/main/java/jext/awt/color"
dest.mkdir(parents=True, exist_ok=True)
colors = dict(sorted(get_named_colors_mapping().items()))
entries = "\n".join(
    f"        matplotlib.put({json.dumps(name)}, new Color(0x{to_hex(value)[1:].upper()}));"
    for name, value in colors.items())
css_entries = "\n".join(
    f'        css.put("{name}", matplotlib.get("{name}"));'
    for name in sorted(CSS4_COLORS))

source = '''package jext.awt.color;

import java.awt.Color;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Named colors from Matplotlib 3.11.2 and HTML/CSS Color 4, rounded to 8-bit sRGB.
 * Includes base shorthand, Tableau, CSS and XKCD names and gray/grey aliases.
 * Generated by tools/generate_named_colors.py; see MATPLOTLIB-LICENSE.txt.
 * Context-dependent CSS keywords and Matplotlib cycle references are not names
 * in this catalog. Hex strings, numeric colors and the special "none" value
 * are not parsed.
 */
public final class NamedColors {
    /** All 1163 entries in Matplotlib's built-in named-color mapping. */
    public static final Map<String, Color> MATPLOTLIB;
    /** The 148 opaque HTML/CSS named colors (including spelling aliases). */
    public static final Map<String, Color> CSS;
    /** Combined catalog, with the CSS transparent keyword added. */
    public static final Map<String, Color> ALL;
    public static final Color TRANSPARENT = new Color(0, true);

    static {
        Map<String, Color> matplotlib = new LinkedHashMap<>();
''' + entries + '''
        MATPLOTLIB = Collections.unmodifiableMap(matplotlib);
        Map<String, Color> css = new LinkedHashMap<>();
''' + css_entries + '''
        CSS = Collections.unmodifiableMap(css);
        Map<String, Color> all = new LinkedHashMap<>(matplotlib);
        all.put("transparent", TRANSPARENT);
        ALL = Collections.unmodifiableMap(all);
    }

    private NamedColors() { }

    /** Returns all canonical names as an unmodifiable set. */
    public static Set<String> names() { return ALL.keySet(); }

    /**
     * Looks up a name case-insensitively, ignoring surrounding whitespace.
     * XKCD and Tableau names retain their prefixes, e.g. "xkcd:sky blue"
     * and "tab:blue". This method also accepts uppercase base shorthand.
     * @throws IllegalArgumentException for null or unknown names
     */
    public static Color get(String name) {
        if (name == null) throw new IllegalArgumentException("Color name is required");
        Color color = ALL.get(name.trim().toLowerCase(Locale.ROOT));
        if (color == null) throw new IllegalArgumentException("Unknown named color: " + name);
        return color;
    }
}
'''
(dest / "NamedColors.java").write_text(source, encoding="utf-8")
fixture = root / "src/test/resources/named-colors.tsv"
fixture.parent.mkdir(parents=True, exist_ok=True)
fixture.write_text("".join(
    f"{name}\t{to_hex(value)[1:]}\t{str(name in CSS4_COLORS).lower()}\n"
    for name, value in colors.items()), encoding="utf-8")
print(f"Generated {len(colors)} Matplotlib names and {len(CSS4_COLORS)} CSS names")
