"""Regenerate Java palettes and reference fixtures with matplotlib==3.11.2.

Run from any directory. Python/Matplotlib are generation tools only, not Java
runtime dependencies. Values use matplotlib.colors.to_hex's 8-bit rounding.
"""
from pathlib import Path
from importlib.metadata import distribution
import matplotlib
from matplotlib.colors import to_hex

VERSION = "3.11.2"
if matplotlib.__version__ != VERSION:
    raise RuntimeError(f"Install matplotlib=={VERSION} to reproduce these tables")
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "src/main/java/jext/awt/color"
DEST.mkdir(parents=True, exist_ok=True)


def class_name(name):
    if name.endswith("_r"):
        return class_name(name[:-2])
    return "".join(part[0].upper() + part[1:] for part in name.split("_"))


names = list(matplotlib.colormaps)
base_names = [n for n in names if not n.endswith("_r")]
assert len({class_name(n).lower() for n in base_names}) == len(base_names)
fixtures = []
for name in base_names:
    cmap = matplotlib.colormaps[name]
    cls = class_name(name)
    values = [to_hex(cmap(i)).upper().replace("#", "0x") for i in range(cmap.N)]
    rows = ["            " + ", ".join(values[i:i+8]) for i in range(0, len(values), 8)]
    reverse = matplotlib.colormaps[name + "_r"]
    reversed_values = [to_hex(reverse(i)).upper().replace("#", "0x") for i in range(reverse.N)]
    reversed_rows = ["            " + ", ".join(reversed_values[i:i+8]) for i in range(0, len(reversed_values), 8)]
    source = f'''package jext.awt.color;

/**
 * Matplotlib {VERSION} colormaps {{@code {name}}} and {{@code {name}_r}} ({cmap.N} colors each).
 * Generated by tools/generate_colormaps.py; see MATPLOTLIB-LICENSE.txt.
 */
public final class {cls} extends ColorMap {{
    private static final int[] RGB = {{
{',\n'.join(rows)}
    }};

    private static final int[] REVERSED_RGB = {{
{',\n'.join(reversed_rows)}
    }};

    public static final {cls} INSTANCE = new {cls}();
    public static final {cls} REVERSED = new {cls}(true);

    public {cls}() {{ this(false); }}

    /** Creates the forward or reversed colormap. */
    public {cls}(boolean reversed) {{
        super(reversed ? "{name}_r" : "{name}", reversed ? REVERSED_RGB : RGB);
    }}
}}
'''
    (DEST / f"{cls}.java").write_text(source, encoding="utf-8")

for name in names:
    cmap = matplotlib.colormaps[name]
    # Independent normalized-value calls exercise binning and clipping in Java.
    points = [-float("inf"), -0.1, 0.0, 0.001, 0.1, 0.25, 0.5, 0.9, 1.0, 1.1, float("inf")]
    points += [(i + 0.5) / cmap.N for i in range(cmap.N)]
    for value in points:
        text = str(value).replace("inf", "Infinity")
        fixtures.append(f"{name}\t{text}\t{to_hex(cmap(value))[1:]}\n")

registrations = "\n".join(
    f"        maps.put(\"{n}\", {class_name(n)}.{'REVERSED' if n.endswith('_r') else 'INSTANCE'});"
    for n in names)
(DEST / "ColorMaps.java").write_text('''package jext.awt.color;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;

/** Built-in Matplotlib colormaps, also used by pandas, keyed by Python name. */
public final class ColorMaps {
    private static final Map<String, ColorMap> MAPS;
    static {
        Map<String, ColorMap> maps = new LinkedHashMap<>();
''' + registrations + '''
        MAPS = Collections.unmodifiableMap(maps);
    }

    private ColorMaps() { }

    public static Set<String> names() { return MAPS.keySet(); }

    public static ColorMap get(String name) {
        ColorMap map = MAPS.get(name);
        if (map == null) throw new IllegalArgumentException("Unknown colormap: " + name);
        return map;
    }
}
''', encoding="utf-8")
resources = ROOT / "src/test/resources"
resources.mkdir(parents=True, exist_ok=True)
(resources / "matplotlib-colormaps.tsv").write_text("".join(fixtures), encoding="utf-8")
dist = distribution("matplotlib")
license_file = next(f for f in dist.files if ".dist-info/" in str(f) and str(f).endswith("/LICENSE"))
(ROOT / "MATPLOTLIB-LICENSE.txt").write_text(dist.locate_file(license_file).read_text(encoding="utf-8"), encoding="utf-8")
print(f"Generated {len(base_names)} paired colormap classes and {len(fixtures)} reference samples")
